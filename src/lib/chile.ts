/** Comunas de una región, o [] si el nombre no corresponde a ninguna. */
export function comunasDe(region: string): string[] {
  return REGIONES.find((r) => r.nombre === region)?.comunas ?? [];
}

/** ¿El par región/comuna existe de verdad? Lo usa la validación del servidor:
 *  el combo del navegador no impide que alguien mande cualquier cosa. */
export function comunaValida(region: string, comuna: string): boolean {
  return comunasDe(region).includes(comuna);
}

/**
 * Dirección en una línea, como se muestra en el correo, el PDF y la pantalla
 * de administración: "Av. Concha y Toro 1234, Puente Alto, Metropolitana de
 * Santiago". Vive acá y no en cada vista para que las tres digan lo mismo.
 */
export function direccionCompleta(
  calle: string,
  comuna: string,
  region: string,
): string {
  return [calle, comuna, region].map((p) => p.trim()).filter(Boolean).join(", ");
}
